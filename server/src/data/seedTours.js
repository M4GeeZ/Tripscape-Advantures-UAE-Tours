export async function seedInitialTours() {
  for (const item of seedTours) {
    await Tour.updateOne(
      { slug: item.slug },
      { $setOnInsert: item },
      { upsert: true },
    )
  }

  const missingOrder = await Tour.find({ sortOrder: { $exists: false } }).sort({ createdAt: 1 }).select('_id').lean()
  if (missingOrder.length) {
    const last = await Tour.findOne({ sortOrder: { $exists: true } }).sort({ sortOrder: -1 }).select('sortOrder').lean()
    let next = Number(last?.sortOrder || 0) + 1
    for (const item of missingOrder) {
      await Tour.updateOne({ _id: item._id }, { $set: { sortOrder: next++ } })
    }
  }
}
